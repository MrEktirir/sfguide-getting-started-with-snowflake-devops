CREATE OR REPLACE VIEW QUICKSTART_PROD.GOLD.ATTRACTIONS AS
SELECT
    a.CITY,
    a.STATE,
    COUNT(DISTINCT CASE
        WHEN p.CATEGORY_MAIN = 'Aquarium'
        THEN p.POI_ID
    END) AS AQUARIUM_COUNT,
    COUNT(DISTINCT CASE
        WHEN p.CATEGORY_MAIN = 'Zoo'
        THEN p.POI_ID
    END) AS ZOO_COUNT,
    COUNT(DISTINCT CASE
        WHEN p.CATEGORY_MAIN = 'Korean Restaurant'
        THEN p.POI_ID
    END) AS KOREAN_RESTAURANT_COUNT
FROM SNOWFLAKE_CURATED_DATA_FREE.PUBLIC_DATA_FREE.POINT_OF_INTEREST_INDEX p
JOIN SNOWFLAKE_CURATED_DATA_FREE.PUBLIC_DATA_FREE.POINT_OF_INTEREST_ADDRESSES_RELATIONSHIPS r
    ON p.POI_ID = r.POI_ID
JOIN SNOWFLAKE_CURATED_DATA_FREE.PUBLIC_DATA_FREE.US_ADDRESSES a
    ON r.ADDRESS_ID = a.ADDRESS_ID
WHERE
    (a.CITY = 'Houston' AND a.STATE = 'TX')
    OR (a.CITY = 'Los Angeles' AND a.STATE = 'CA')
    OR (a.CITY = 'New York' AND a.STATE = 'NY')
GROUP BY a.CITY, a.STATE;
